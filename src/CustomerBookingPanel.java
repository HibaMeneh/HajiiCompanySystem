    private void btnCancelBookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelBookingActionPerformed
int row = tblMyBookings.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this,
            "Please select a booking first");
        return;
    }

    String status = tblMyBookings.getValueAt(row, 4).toString();
    if (status.equalsIgnoreCase("approved")) {
        JOptionPane.showMessageDialog(this,
            "Approved booking cannot be cancelled");
        return;
    }

    int bookingId = Integer.parseInt(
        tblMyBookings.getValueAt(row, 0).toString()
    );

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to cancel this booking?",
        "Confirm",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) return;

    try {
        String sql =
            "UPDATE bookings SET status='cancelled' WHERE booking_id=?";
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, bookingId);
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
            "Booking cancelled successfully");
        loadMyBookings();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Cancel Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnCancelBookingActionPerformed

