private void loadMyBookings() {
    try {
        DefaultTableModel model = (DefaultTableModel) tblMyBookings.getModel();
        model.setRowCount(0);

        String sql =
            "SELECT b.booking_id, p.package_name, p.start_date, p.end_date, " +
            "b.status, b.total_price " +
            "FROM bookings b " +
            "JOIN packages p ON b.package_id = p.package_id " +
            "WHERE b.hajji_id = ? " +
            "ORDER BY b.booking_id";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, loggedHajjiId);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("booking_id"),
                rs.getString("package_name"),
                rs.getDate("start_date"),
                rs.getDate("end_date"),
                rs.getString("status"),
                rs.getBigDecimal("total_price")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Load Booking Error: " + e.getMessage());
    }
}

