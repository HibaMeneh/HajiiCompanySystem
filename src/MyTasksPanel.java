    private void btnMarkDoneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarkDoneActionPerformed
        int row = tblTasks.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a task first.");
        return;
    }

    int taskId = Integer.parseInt(tblTasks.getValueAt(row, 0).toString());

    try {
        String sql = "UPDATE employee_tasks SET status='Done' WHERE task_id=? AND emp_id=?";
        pst = con.prepareStatement(sql);
        pst.setInt(1, taskId);
        pst.setInt(2, loggedEmpId);

        int updated = pst.executeUpdate();
        if (updated > 0) {
            JOptionPane.showMessageDialog(this, "Task marked as Done!");
            loadTasks();
        } else {
            JOptionPane.showMessageDialog(this, "No task updated (check task belongs to you).");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Update Error: " + e.getMessage());
    }
loadTasks();
loadTaskCounters();// TODO add your handling code here:
    }//GEN-LAST:event_btnMarkDoneActionPerformed

