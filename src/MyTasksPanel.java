    private void setupTableClick() {
         tblTasks.getSelectionModel().addListSelectionListener(e -> {
        int row = tblTasks.getSelectedRow();
        if (row != -1) {
            String status = tblTasks.getValueAt(row, 3).toString();
            cmbStatus.setSelectedItem(status);
        }
    });
    }

    private void loadTasks() {
        try {
        String sql =
            "SELECT task_id, title, description, status, due_date " +
            "FROM employee_tasks " +
            "WHERE emp_id = ? " +
            "ORDER BY due_date";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedEmpId);
        rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblTasks.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("task_id"),
                rs.getString("title"),
                rs.getString("description"),
                rs.getString("status"),
                rs.getDate("due_date")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Load Tasks Error: " + e.getMessage());
    }
    }

 private void loadTaskCounters() {
    try {
        String sql =
            "SELECT " +
            "SUM(CASE WHEN status = 'Pending' THEN 1 ELSE 0 END) AS pending_count, " +
            "SUM(CASE WHEN status = 'Done' THEN 1 ELSE 0 END) AS done_count " +
            "FROM employee_tasks WHERE emp_id = ?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedEmpId);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblPending.setText("Pending Tasks: " + rs.getInt("pending_count"));
            lblDone.setText("Done Tasks: " + rs.getInt("done_count"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Counter Error: " + e.getMessage());
    }
}
