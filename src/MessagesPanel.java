    private void loadMessages() {
      try {
        String sql =
            "SELECT message_id, sender, message, sent_at, status " +
    "FROM employee_Messagess " +
    "WHERE emp_id=? " +
    "ORDER BY sent_at DESC";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedEmpId);
        rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblMessages.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("message_id"),
                rs.getString("sender"),
                rs.getString("message"),
                rs.getTimestamp("sent_at"),
                rs.getString("status")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Load Messages Error: " + e.getMessage());
    }
    }

    private void loadUnreadCounter() {
        try {
        String sql =
    "SELECT COUNT(*) FROM employee_Messagess " +
    "WHERE emp_id=? AND status='Unread'";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedEmpId);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblUnreadCount.setText("Unread Messages: " + rs.getInt(1));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Counter Error: " + e.getMessage());
    }
    }
