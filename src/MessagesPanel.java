    private void btnReplyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReplyActionPerformed
int row = tblMessages.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a message first");
        return;
    }

    JTextArea txtReply = new JTextArea(5, 30);
    txtReply.setLineWrap(true);
    txtReply.setWrapStyleWord(true);

    int option = JOptionPane.showConfirmDialog(
        this,
        new JScrollPane(txtReply),
        "Reply Message",
        JOptionPane.OK_CANCEL_OPTION
    );

    if (option == JOptionPane.OK_OPTION) {
        String reply = txtReply.getText().trim();

        if (reply.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Reply cannot be empty");
            return;
        }

        try {
            String sql =
                "INSERT INTO employee_messages (emp_id, sender, message, status) " +
                "VALUES (?, 'Employee', ?, 'Unread')";

            pst = con.prepareStatement(sql);
            pst.setInt(1, loggedEmpId);
            pst.setString(2, reply);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Reply sent successfully!");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Reply Error: " + e.getMessage());
        }
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnReplyActionPerformed

