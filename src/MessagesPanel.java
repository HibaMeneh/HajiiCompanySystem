    private void btnMarkReadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarkReadActionPerformed
int row = tblMessages.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Select a message first");
        return;
    }

    int msgId = Integer.parseInt(tblMessages.getValueAt(row, 0).toString());

    try {
        String sql =
           "UPDATE employee_Messagess SET status='Read' " +
    "WHERE message_id=? AND emp_id=?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, msgId);
        pst.setInt(2, loggedEmpId);
        pst.executeUpdate();

        loadMessages();
        loadUnreadCounter();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Update Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnMarkReadActionPerformed

