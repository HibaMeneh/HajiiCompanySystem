    private void btnCancelTransportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelTransportActionPerformed
int row = tblMyTransport.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this,
            "Please select a transport first");
        return;
    }

    String status = tblMyTransport.getValueAt(row, 6).toString();
    if (status.equalsIgnoreCase("approved")) {
        JOptionPane.showMessageDialog(this,
            "Approved transport cannot be cancelled");
        return;
    }

    int transportId = Integer.parseInt(
        tblMyTransport.getValueAt(row, 0).toString()
    );

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to cancel this transport?",
        "Confirm",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) return;

    try {
        String sql =
            "UPDATE hajji_transports SET status='cancelled' " +
            "WHERE hajji_id=? AND transport_id=?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedHajjiId);
        pst.setInt(2, transportId);
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
            "Transport cancelled successfully");
        loadMyTransport();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Cancel Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnCancelTransportActionPerformed

