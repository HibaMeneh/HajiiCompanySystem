    private void loadMyTransport() {
         try {
        DefaultTableModel model =
            (DefaultTableModel) tblMyTransport.getModel();
        model.setRowCount(0);

        String sql =
            "SELECT t.transport_id, c.company_name, t.vehicle_type, " +
            "t.from_location, t.to_location, t.departure_date, ht.status " +
            "FROM hajji_transports ht " +
            "JOIN transports t ON ht.transport_id = t.transport_id " +
            "JOIN transport_companies c ON t.company_id = c.company_id " +
            "WHERE ht.hajji_id = ? " +
            "ORDER BY t.departure_date";

        pst = con.prepareStatement(sql);
        pst.setInt(1, loggedHajjiId);
        rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[] {
                rs.getInt("transport_id"),
                rs.getString("company_name"),
                rs.getString("vehicle_type"),
                rs.getString("from_location"),
                rs.getString("to_location"),
                rs.getDate("departure_date"),
                rs.getString("status")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Load Transport Error: " + e.getMessage());
    }
    }
