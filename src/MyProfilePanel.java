    private void btnSortBySalaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSortBySalaryActionPerformed
 try {
        pst = con.prepareStatement(
            "SELECT emp_id, first_name, last_name, email, gender, salary " +
            "FROM employees ORDER BY salary DESC"
        );
        rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblMyInfo.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("emp_id"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("email"),
                rs.getString("gender"),
                rs.getBigDecimal("salary")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Sort Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSortBySalaryActionPerformed

