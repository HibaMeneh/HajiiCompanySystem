    private void setupTable() {
        DefaultTableModel model = new DefaultTableModel(
        new Object[]{"Employee_id","first_name","last_name","Email","Gender","Salary"}, 0
    ) {
        @Override
        public boolean isCellEditable(int row, int col) {
            return false; // ممنوع التعديل من الجدول
        }
    };
    tblMyInfo.setModel(model);
    }

    private void loadMyData() {
      try {
        pst = con.prepareStatement(
            "SELECT emp_id, first_name, last_name, email, gender, salary " +
            "FROM employees WHERE emp_id = ?"
        );
        pst.setInt(1, loggedEmpId);

        rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tblMyInfo.getModel();
        model.setRowCount(0);

        if (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("emp_id"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("email"),
                rs.getString("gender"),
                rs.getDouble("salary")
            });

            // تعبئة الحقول فوق
            txtFirstName.setText(rs.getString("first_name"));
            txtLastName.setText(rs.getString("last_name"));
            txtEmail.setText(rs.getString("email"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }
