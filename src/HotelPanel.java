    private void loadMyHotels() {
        try {
            DefaultTableModel model =
                (DefaultTableModel) tblMyHotels.getModel();
            model.setRowCount(0);

            String sql =
                "SELECT hb.booking_id, h.hotel_name, h.city, " +
                "hb.room_type, hb.check_in, hb.check_out, " +
                "hb.status, hb.price " +
                "FROM hotel_bookings hb " +
                "JOIN hotels h ON hb.hotel_id = h.hotel_id " +
                "WHERE hb.hajji_id = ? " +
                "ORDER BY hb.booking_id";

            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, loggedHajjiId);
            ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("booking_id"),
                    rs.getString("hotel_name"),
                    rs.getString("city"),
                    rs.getString("room_type"),
                    rs.getDate("check_in"),
                    rs.getDate("check_out"),
                    rs.getString("status"),
                    rs.getBigDecimal("price")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Load Hotel Error: " + e.getMessage());
        }
    
    }
