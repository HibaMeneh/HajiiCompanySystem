    private void btnCancelHotelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelHotelActionPerformed
int row = tblMyHotels.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this,
                "Please select a hotel booking first");
            return;
        }

        String status = tblMyHotels.getValueAt(row, 6).toString();
        if (status.equalsIgnoreCase("approved")) {
            JOptionPane.showMessageDialog(this,
                "Approved booking cannot be cancelled");
            return;
        }

        int bookingId =
            Integer.parseInt(tblMyHotels.getValueAt(row, 0).toString());

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to cancel this hotel booking?",
            "Confirm",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) return;

        try {
            String sql =
                "UPDATE hotel_bookings SET status='cancelled' WHERE booking_id=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, bookingId);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this,
                "Hotel booking cancelled successfully");
            loadMyHotels();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Cancel Error: " + e.getMessage());
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnCancelHotelActionPerformed

